/* ---- Derived values -------------------------------------------------
   Durations always roll up from leaves, so nothing is hand-totalled and
   the numbers can't drift from the content. A disabled title card is
   excluded: it won't play, so it contributes no time. A hidden object is
   excluded too -- it isn't in the overview yet, so counting its time would
   make the total disagree with the visible list. Clearing o.hidden at
   demo time and re-rendering makes both update together. */

function fmtMSS(totalSeconds) {
  const m = Math.floor(totalSeconds / 60);
  const s = totalSeconds % 60;
  return m + ':' + String(s).padStart(2, '0');
}

function fmtCourse(totalSeconds) {
  const m = Math.floor(totalSeconds / 60);
  const s = totalSeconds % 60;
  return m + 'm ' + s + 's';
}

function sectionSeconds(section) {
  return section.objects.reduce(
    (sum, o) => sum + (o.disabled || o.hidden ? 0 : o.dur), 0);
}

function courseSeconds(course) {
  return course.sections.reduce((sum, s) => sum + sectionSeconds(s), 0);
}

function courseProgress(course) {
  let done = 0, total = 0;
  course.sections.forEach(s => s.objects.forEach(o => {
    // A hidden object isn't on the overview yet, so it can't be counted --
    // otherwise the denominator jumps when the rep reveals it.
    if (o.hidden) return;
    total++;
    // Shipped content is finalized, so it counts as complete. The
    // generated flag marks the LO revealed during the demo: it never went
    // through publishing, so it stays outstanding. Same rule the rows use.
    if (o.state === 'complete' || !o.generated) done++;
  }));
  return { done, total };
}

function findObject(course, objectId) {
  for (const section of course.sections) {
    const obj = section.objects.find(o => o.id === objectId);
    if (obj) return { section, obj };
  }
  return null;
}
